def hx(v, n=4):
    return '0x%0*X' % (n, v)

def carray(ctype, name, vals, per=16, fmt=None):
    fmt = fmt or (lambda v: hx(v) if 'u16' in ctype else str(v))
    lines = []
    for i in range(0, len(vals), per):
        lines.append('    ' + ', '.join(fmt(v) for v in vals[i:i + per]) + ',')
    return 'const %s %s[%d] = {\n%s\n};\n' % (ctype, name, len(vals), '\n'.join(lines))

def c12(s):
    r, g, b = (int(ch, 16) for ch in s)
    return r | (g << 4) | (b << 8)

# ------------------------------------------------------------------ road
# The road image is 256 px wide (the whole SCR2 map) with its centre at x=128.
# Source rows j = 0..87 run from the horizon (half width ~1, so the road
# vanishes at the horizon) to the bumper (half width ROAD_HB: wider than the
# screen, the edges are off-screen when the car is centred, as in the arcade).
#
# A 256 px map row cannot hold a road this wide once the camera follows the car
# to the verge: the 160 px window would wrap around and show the far side.
# The near rows (j >= ROAD_WIDE0) are therefore stored twice more, re-centred
# ROAD_VSHIFT px to the right / left; the raster picks the copy whose window
# fits (id_road.c, wide_rows()).
ROAD_ROWS = 88
ROAD_LANES = 4
ROAD_HB = 140
ROAD_WIDE0 = 48
ROAD_VSHIFT = 96
ROAD_CAM_MAX = 144          # max camera shear on the wide rows

def road_half(j):
    return max(1, int(round(1 + (ROAD_HB - 1) * j / (ROAD_ROWS - 1.0))))

ROAD_HALF = [road_half(j) for j in range(ROAD_ROWS)]

def road_px(j, off):
    """true colour index of road row j at lateral offset off (px from centre)"""
    half = ROAD_HALF[j]
    ew = max(1, half // 14)          # white edge line
    sw = max(1, half // 9)           # rumble strip outside the edge
    lw = max(1, half // 22)          # lane dashes
    ad = abs(off + 0.5)
    if ad < half:
        v = 1
        if ad >= half - ew:
            v = 3
        for k in range(1, ROAD_LANES):      # lane dividers
            pos = half * (2.0 * k - ROAD_LANES) / ROAD_LANES
            if abs(off + 0.5 - pos) < lw / 2.0 + 0.25:
                v = 2
        return v
    if ad < half + sw:
        return 2
    return 0

def road_row(j, shift=0):
    return [road_px(j, x - 128 + shift) for x in range(256)]

def road_lim0(j):
    """smallest |camera shear| for which the plain row shows wrong pixels"""
    r = road_row(j)
    for dx in range(0, 200):
        for sgn in (1, -1):
            c = dx * sgn
            for p in range(160):
                off = c - 80 + p
                if r[(128 + off) % 256] != road_px(j, off):
                    return dx
    return 200

def gen_road():
    W = 256
    rows = [[0] * W for _ in range(64)]
    rows += [road_row(j) for j in range(ROAD_ROWS)]
    rows += [road_row(j, ROAD_VSHIFT) for j in range(ROAD_WIDE0, ROAD_ROWS)]
    rows += [road_row(j, -ROAD_VSHIFT) for j in range(ROAD_WIDE0, ROAD_ROWS)]
    assert len(rows) % 8 == 0
    H = len(rows) // 8
    assert 11 + H - 8 <= 32, 'road image does not fit under the panorama'
    lim0 = [road_lim0(j) for j in range(ROAD_ROWS)]
    # the shifted copies must be exact for every shear the wide rows can get
    for j in range(ROAD_WIDE0, ROAD_ROWS):
        rp = road_row(j, ROAD_VSHIFT)
        for c in range(lim0[j], ROAD_CAM_MAX + 1):
            for p in range(160):
                off = c - 80 + p
                assert rp[(128 + off - ROAD_VSHIFT) % 256] == road_px(j, off), (j, c)
    tiles, index, mapv = [], {}, []
    from ngpgfx import pixels_to_words
    for ty in range(H):
        for tx in range(W // 8):
            words = tuple(pixels_to_words([rows[ty * 8 + y][tx * 8:tx * 8 + 8] for y in range(8)]))
            if words not in index:
                index[words] = len(tiles)
                tiles.append(words)
            mapv.append(index[words])
    pal = [0x0052, 0x0333, 0x0555, 0x0FFF]
    pals = pal + pal + [0] * 56
    hdr = ['/* Generated by tools/gen_gfx.py -- SUNSET RUN road. */',
           '#ifndef ID_ROUTE_INCLUDED', '#define ID_ROUTE_INCLUDED', '#include "ngpc_types.h"',
           '#define ID_ROUTE_W  %d' % (W // 8), '#define ID_ROUTE_H  %d' % H,
           '#define ID_ROUTE_ROAD_TOP     64', '#define ID_ROUTE_ROAD_BOTTOM  151',
           '#define ID_ROUTE_WIDE0    %du   /* first source row with shifted copies */' % ROAD_WIDE0,
           '#define ID_ROUTE_VSHIFT   %du   /* lateral shift of the copies (px) */' % ROAD_VSHIFT,
           '#define ID_ROUTE_VROWS    %du   /* rows from a row to its +shift copy */' % (ROAD_ROWS - ROAD_WIDE0),
           '#define ID_ROUTE_CAM_MAX  %d' % ROAD_CAM_MAX,
           'extern const u16 id_route_tiles_count;', 'extern const u16 id_route_tiles[];',
           'extern const u8  id_route_palette_count;', 'extern const u16 id_route_palettes[];',
           'extern const u16 id_route_map[];', 'extern const u8  id_route_map_pal[];',
           'extern const u8  id_route_road_half[];', 'extern const u8  id_route_lim0[];',
           '#endif', '']
    open(os.path.join(OUT, 'id_route.h'), 'w').write('\n'.join(hdr))
    c = ['/* Generated by tools/gen_gfx.py -- SUNSET RUN road (4 lanes). */',
         '#include "id_route.h"',
         'const u16 id_route_tiles_count = %d;' % (len(tiles) * 8),
         carray('u16', 'id_route_tiles', [w for t in tiles for w in t], 8),
         'const u8 id_route_palette_count = 16;',
         carray('u16', 'id_route_palettes', pals, 4),
         carray('u16', 'id_route_map', mapv, 32),
         carray('u8', 'id_route_map_pal', [0] * len(mapv), 32),
         carray('u8', 'id_route_road_half', ROAD_HALF, 16),
         carray('u8', 'id_route_lim0', [min(255, v) for v in lim0], 16)]
    open(os.path.join(OUT, 'id_route.c'), 'w').write('\n'.join(c))
    print('road: %d tiles, %d tile rows' % (len(tiles), H))
    return [r[48:208] for r in rows]

# ------------------------------------------------------------------ player car
PLAYER_PAL_A = ['720', 'E21', 'F73']      # dark red / chestnut hair, red, tail lamps (RGB)
PLAYER_PAL_B = ['111', 'CCD', 'FD6']      # black, chrome, blonde

def car_pose(grid, k):
    """synthesised turn pose k (0..2): top leans, side panel shows on the left."""
    if k == 0:
        return list(grid)
    out = []
    H = len(grid)
    for y, row in enumerate(grid):
        shift = round(k * (H - 1 - y) / 12.0)
        r = row
        if 7 <= y <= 17 and k:
            # side panel: extend the body by k pixels of dark red on the left
            first = next((i for i, ch in enumerate(r) if ch != '.'), None)
            if first is not None:
                r = r[:max(0, first - k)] + 'r' * min(k, first) + r[first:]
                r = r[:32]
        r = ('.' * shift + r)[:32] if shift else r
        out.append(r.ljust(32, '.'))
    return out

def gen_player():
    tiles = []
    tindex = {}
    pose_cells, pose_first, pose_w = [], [], []
    cells = []
    # 0 straight, 1 leaning right, 2 leaning left.  Leaning left is the
    # mirror image, but the passengers must not swap seats: the left poses
    # are the mirrored car without the heads, plus the heads re-drawn
    # unmirrored (driver left, blonde passenger right).
    def mirror(g):
        return [r[::-1] for r in g]
    H = len(art.PLAYER)
    heads, nohead = {}, []
    for y, row in enumerate(art.PLAYER):
        r = list(row)
        if y <= 6:
            for x, ch in enumerate(row):
                if (8 <= x <= 14 and ch in 'rK') or (17 <= x <= 26 and ch in 'YK'):
                    heads[(x, y)] = ch
                    r[x] = 'W' if y == 6 else '.'
        nohead.append(''.join(r))
    def left_pose(k):
        g = [list(r) for r in mirror(car_pose(nohead, k))]
        for (x, y), ch in heads.items():
            x2 = x - round(k * (H - 1 - y) / 12.0)
            if 0 <= x2 < 32:
                g[y][x2] = ch
        return [''.join(r) for r in g]
    # three poses (VRAM is tight): straight, leaning right, leaning left
    poses = [car_pose(art.PLAYER, 0), car_pose(art.PLAYER, 2), left_pose(2)]
    # layer 0 (palette A, body) then layer 1 (palette B, trim)
    for layer, slots in enumerate([art.PLAYER_LAYER_A, art.PLAYER_LAYER_B]):
        for p in poses:
            cl, wc, hc = sprite_tiles(p, slots)
            pose_first.append(len(cells))
            pose_cells.append(len(cl))
            pose_w.append(wc)
            for cx, cy, words in cl:
                if words not in tindex:
                    tindex[words] = len(tiles)
                    tiles.append(words)
                cells.append((cx, cy, tindex[words]))
    pal = [0] + [c12(c) for c in PLAYER_PAL_A] + [0] + [c12(c) for c in PLAYER_PAL_B]
    h = ['/* Generated by tools/gen_gfx.py -- SUNSET RUN player convertible. */',
         '#ifndef ID_CAROG_H', '#define ID_CAROG_H', '#include "ngpc_types.h"',
         '#ifndef ID_CAR_CELL_DEFINED', '#define ID_CAR_CELL_DEFINED',
         'typedef struct { u8 cx, cy, ch; } IdCarCell;', '#endif',
         '#define ID_CAROG_LAYERS  2', '#define ID_CAROG_POSES   3',
         '#define ID_CAROG_HEIGHT  %d' % len(art.PLAYER), '#define ID_CAROG_ANGLES  4',
         '#define ID_CAROG_RACE_POSES  3', '#define ID_CAROG_RACE_CHARS  %d' % len(tiles),
         'extern const u16 id_carog_tiles_count;', 'extern const u16 id_carog_tiles[];',
         'extern const u16 id_carog_palette[8];', 'extern const u8  id_carog_pose_cells[];',
         'extern const u8  id_carog_pose_first[];', 'extern const u8  id_carog_pose_w[];',
         'extern const IdCarCell id_carog_cells[];', '#endif', '']
    open(os.path.join(OUT, 'id_carog.h'), 'w').write('\n'.join(h))
    c = ['/* Generated by tools/gen_gfx.py -- do not edit. */', '#include "id_carog.h"',
         'const u16 id_carog_tiles_count = %d;' % (len(tiles) * 8),
         carray('u16', 'id_carog_tiles', [w for t in tiles for w in t], 8),
         carray('u16', 'id_carog_palette', pal, 8),
         carray('u8', 'id_carog_pose_cells', pose_cells),
         carray('u8', 'id_carog_pose_first', pose_first),
         carray('u8', 'id_carog_pose_w', pose_w),
         'const IdCarCell id_carog_cells[%d] = {\n%s\n};\n' % (len(cells), '\n'.join('    { %d, %d, %d },' % c for c in cells))]
    open(os.path.join(OUT, 'id_carog.c'), 'w').write('\n'.join(c))
    return poses, len(tiles)

