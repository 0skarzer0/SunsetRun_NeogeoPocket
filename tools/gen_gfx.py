def gen_scaled(prefix, items, widths_fn):
    """Emit one C file with a tile pool and per-(kind,rung) frames."""
    tiles, tindex, cells, frames = [], {}, [], []
    previews = {}
    for kind, grid in items:
        wmax = max(len(r) for r in grid)
        for rung, nw in enumerate(widths_fn(kind, wmax)):
            g = scale_grid(grid, max(2, nw))
            pad = (-len(g)) % 8          # bottom-align: pad on top
            g = ['.' * len(g[0])] * pad + g
            cl, wc, hc = sprite_tiles(g, 'abc')
            first = len(cells)
            for cx, cy, words in cl:
                if words not in tindex:
                    tindex[words] = len(tiles)
                    tiles.append(words)
                cells.append((cx, cy, tindex[words]))
            frames.append((wc, hc, len(cl), first, len(g[0]), len(g)))
            previews[(kind, rung)] = g
    lines = ['/* Generated by tools/gen_gfx.py -- do not edit. */', '#include "gfx_sprites.h"',
             'const u16 %s_tiles_count = %d;' % (prefix, len(tiles)),
             carray('u16', '%s_tiles' % prefix, [w for t in tiles for w in t], 8),
             'const SprCell %s_cells[%d] = {\n%s\n};' % (prefix, len(cells), '\n'.join('    { %d, %d, %d },' % c for c in cells)),
             'const SprFrame %s_frames[%d] = {\n%s\n};' % (prefix, len(frames), '\n'.join('    { %d, %d, %d, %d, %d, %d },' % f for f in frames))]
    return '\n'.join(lines) + '\n', len(tiles), previews

