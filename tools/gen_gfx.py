def gen_panos():
    srcs = ['/* Generated by tools/gen_gfx.py -- do not edit. */', '#include "gfx_pano.h"']
    hdr = ['/* Generated by tools/gen_gfx.py -- do not edit. */', '#ifndef GFX_PANO_H', '#define GFX_PANO_H',
           '#include "ngpc_types.h"', '#define GFX_PANO_COUNT %d' % len(PANO_ORDER),
           '#define GFX_PANO_ROWS 11',
           'typedef struct { const u16 *tiles; u16 count; const u8 *map; const u8 *map_pal; const u16 *pals; u16 backdrop; } PanoArt;',
           'extern const PanoArt gfx_pano[GFX_PANO_COUNT];']
    entries = []
    imgs = {}
    maxt = 0
    for name in PANO_ORDER:
        img, bd = pano.THEMES[name]()
        img = pano.finish(img, bd)
        r = convert_plane(img, bd, max_pals=13)
        maxt = max(maxt, len(r['tiles']))
        n = 'pano_' + name
        srcs.append(carray('u16', n + '_tiles', [w for t in r['tiles'] for w in t], 8))
        srcs.append(carray('u8', n + '_map', r['map'], 32))
        srcs.append(carray('u8', n + '_map_pal', r['map_pal'], 32))
        srcs.append(carray('u16', n + '_pals', [c for p in r['palettes'] for c in p], 4))
        entries.append('    { %s_tiles, %d, %s_map, %s_map_pal, %s_pals, 0x%04X },' % (n, len(r['tiles']), n, n, n, to12(bd)))
        hdr.append('#define PANO_%s %d' % (name.upper(), len(entries) - 1))
        imgs[name] = r
    srcs.append('const PanoArt gfx_pano[GFX_PANO_COUNT] = {\n%s\n};\n' % '\n'.join(entries))
    hdr.append('#define GFX_PANO_MAX_TILES %d' % maxt)
    hdr += ['#endif', '']
    open(os.path.join(OUT, 'gfx_pano.c'), 'w').write('\n'.join(srcs))
    open(os.path.join(OUT, 'gfx_pano.h'), 'w').write('\n'.join(hdr))
    return imgs, maxt

def grid_img(g, pal):
    im = Image.new('RGBA', (len(g[0]), len(g)), (0, 0, 0, 0))
    for y, row in enumerate(g):
        for x, ch in enumerate(row):
            if ch in pal:
                im.putpixel((x, y), rgb12(c12(pal[ch])) + (255,))
    return im


