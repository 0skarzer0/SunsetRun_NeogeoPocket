def crowd(w=24, h=16):
    """two rows of fans; the front row alternates arms up / arms out
    (drawn mirrored every few frames, which reads as cheering)"""
    g = blank(w, h)
    # back row: heads and raised hands between the front fans
    for i in range(4):
        x0 = 3 + i * 6
        for x in (x0, x0 + 1):
            put(g, x, 2, 'a'); put(g, x, 3, 'c')
        put(g, x0 - 1, 0, 'c'); put(g, x0 - 1, 1, 'c'); put(g, x0 + 2, 0, 'c'); put(g, x0 + 2, 1, 'c')
        for x in range(x0 - 1, x0 + 3):
            put(g, x, 4, 'b'); put(g, x, 5, 'b')
    for i in range(4):
        x0 = i * 6
        up = (i % 2 == 0)
        for x in range(x0 + 1, x0 + 4):
            put(g, x, 6, 'a')
            put(g, x, 7, 'c')
            put(g, x, 8, 'c')
        for y in range(9, h - 2):
            for x in range(x0 + 1, x0 + 4):
                put(g, x, y, 'b')
        put(g, x0 + 1, h - 2, 'a'); put(g, x0 + 3, h - 2, 'a')
        put(g, x0 + 1, h - 1, 'a'); put(g, x0 + 3, h - 1, 'a')
        if up:
            for k in range(4):
                put(g, x0, 9 - k, 'c'); put(g, x0 + 4, 9 - k, 'c')
        else:
            put(g, x0, 10, 'c'); put(g, x0, 11, 'c')
            put(g, x0 + 4, 9, 'c'); put(g, x0 + 5, 8, 'c'); put(g, x0 + 5, 7, 'c')
    return done(g)


def trophy(w=16, h=24):
    """golden cup: a = shadow, b = gold, c = highlight"""
    g = blank(w, h)
    for y in range(0, 12):
        half = 7 - max(0, y - 6) // 1
        half = min(7, max(2, 7 - max(0, y - 7)))
        for x in range(8 - half, 8 + half):
            ch = 'b'
            if x < 8 - half + 2:
                ch = 'c'
            if x >= 8 + half - 2:
                ch = 'a'
            if y == 0:
                ch = 'a' if x in (8 - half, 8 + half - 1) else 'c'
            put(g, x, y, ch)
    for y in range(2, 8):                      # handles
        put(g, 0, y, 'b'); put(g, 15, y, 'a')
    put(g, 1, 1, 'b'); put(g, 14, 1, 'a'); put(g, 1, 8, 'b'); put(g, 14, 8, 'a')
    for y in range(12, 17):                    # stem
        put(g, 7, y, 'c'); put(g, 8, y, 'a')
    for y in range(17, 24):                    # base
        for x in range(3, 13):
            put(g, x, y, 'a' if y in (17, 23) else ('c' if x < 6 else 'b'))
    return done(g)
