# ---------------------------------------------------------------- windmill
def windmill(w=24, h=32):
    """white round tower, dark conical cap, four lattice sails"""
    g = blank(w, h)
    cx = 12
    # tower (y 12..31), slightly tapered, lit from the right
    for y in range(12, h):
        half = 4 + (y - 12) * 2 // 19
        for x in range(cx - half, cx + half + 1):
            ch = 'b'
            if x <= cx - half + 1:
                ch = 'a'
            elif x >= cx + 1:
                ch = 'c'
            put(g, x, y, ch)
    # door and window
    for y in range(26, 31):
        put(g, cx, y, 'a'); put(g, cx + 1, y, 'a')
    put(g, cx, 17, 'a'); put(g, cx, 18, 'a')
    # cap
    for y in range(8, 13):
        half = (y - 8) + 1
        for x in range(cx - half, cx + half + 1):
            put(g, x, y, 'a' if x < cx + 1 else 'b')
    # sails around the hub (cx, 11), two diagonals
    hub = (cx, 11)
    for ang in (math.radians(25), math.radians(115), math.radians(205), math.radians(295)):
        for r in range(2, 12):
            x = hub[0] + r * math.cos(ang)
            y = hub[1] - r * math.sin(ang)
            put(g, int(round(x)), int(round(y)), 'a')
            # lattice cloth beside the spar
            if r > 3:
                ox = -math.sin(ang) * 2.0
                oy = -math.cos(ang) * 2.0
                put(g, int(round(x + ox)), int(round(y + oy)), 'c' if r % 2 else 'b')
                put(g, int(round(x + ox / 2)), int(round(y + oy / 2)), 'c')
    put(g, hub[0], hub[1], 'a')
    return done(g)

# ---------------------------------------------------------------- broad tree
def tree(w=24, h=28, seed=3):
    """round crowned tree: clustered canopy with light top-right, dark trunk"""
    import random
    rnd = random.Random(seed)
    g = blank(w, h)
    blobs = [(12, 8, 7), (6, 11, 5), (18, 11, 5), (9, 5, 4), (15, 5, 4), (12, 13, 6)]
    for bx, by, r in blobs:
        for y in range(by - r, by + r + 1):
            for x in range(bx - r, bx + r + 1):
                d = math.hypot(x - bx, (y - by) * 1.1)
                if d <= r - (0.6 if rnd.random() < 0.25 else 0):
                    lit = (x - bx) * 0.5 - (y - by) * 0.8
                    ch = 'c' if lit > r * 0.35 else ('a' if lit < -r * 0.45 else 'b')
                    if g[y][x] == '.' or ch != 'b':
                        put(g, x, y, ch)
    # speckle the canopy
    for _ in range(40):
        x, y = rnd.randrange(w), rnd.randrange(19)
        if g[y][x] == 'b':
            g[y][x] = rnd.choice('ac')
    # trunk and branches
    for y in range(15, h):
        put(g, 11, y, 'a'); put(g, 12, y, 'a')
        if y > h - 4:
            put(g, 10, y, 'a'); put(g, 13, y, 'a')
    for i in range(4):
        put(g, 10 - i, 16 - i, 'a'); put(g, 13 + i, 16 - i, 'a')
    return done(g)

# ---------------------------------------------------------------- poplar
def poplar(w=12, h=32):
    g = blank(w, h)
    cx = 6
    for y in range(0, 27):
        t = y / 26.0
        half = 0.8 + 4.6 * math.sin(math.pi * min(1.0, t * 1.15)) ** 0.8
        for x in range(w):
            d = x - cx + 0.5
            if abs(d) <= half:
                ch = 'c' if d > half * 0.3 else ('a' if d < -half * 0.4 else 'b')
                if (x * 3 + y * 5) % 7 == 0:
                    ch = 'a'
                put(g, x, y, ch)
    for y in range(26, h):
        put(g, cx - 1, y, 'a'); put(g, cx, y, 'a')
    return done(g)

# ---------------------------------------------------------------- ruined column
def column(w=16, h=32):
    g = blank(w, h)
    # capital
    for x in range(1, 15):
        put(g, x, 2, 'b'); put(g, x, 3, 'a')
    for x in range(2, 14):
        put(g, x, 1, 'c')
    put(g, 3, 0, 'c'); put(g, 4, 0, 'c'); put(g, 9, 0, 'c')     # broken top
    # fluted shaft
    for y in range(4, h - 3):
        for x in range(3, 13):
            flute = (x - 3) % 3
            ch = 'c' if flute == 1 and x > 7 else ('a' if flute == 0 else 'b')
            if x <= 4:
                ch = 'a'
            put(g, x, y, ch)
        if y in (12, 21):                      # drum joints
            for x in range(3, 13):
                put(g, x, y, 'a')
    # base
    for y in range(h - 3, h):
        for x in range(1, 15):
            put(g, x, y, 'b' if y < h - 1 else 'a')
    return done(g)

# ---------------------------------------------------------------- signs
def curve_sign_big(w=24, h=24):
    """warning board: white panel, red bent arrow pointing LEFT, two legs"""
    g = blank(w, h)
    for y in range(0, 15):
        for x in range(0, w):
            edge = y in (0, 14) or x in (0, w - 1)
            put(g, x, y, 'a' if edge else 'c')
    # bent arrow: shaft comes up from the bottom right, turns left
    for y in range(6, 13):
        for x in (15, 16, 17):
            put(g, x, y, 'b')
    for x in range(8, 17):
        for y in (5, 6, 7):
            put(g, x, y, 'b')
    for i in range(5):            # arrow head pointing left
        for y in range(6 - i, 7 + i):
            put(g, 4 + i, y, 'b')
    for y in range(15, h):
        put(g, 5, y, 'a'); put(g, 6, y, 'a')
        put(g, w - 7, y, 'a'); put(g, w - 6, y, 'a')
    return done(g)

def fork_sign_big(w=24, h=24):
    """junction board: green panel with a white Y and a left arrow tip"""
    g = blank(w, h)
    for y in range(0, 16):
        for x in range(0, w):
            edge = y in (0, 15) or x in (0, w - 1)
            put(g, x, y, 'c' if edge else 'b')
    # the Y
    for y in range(9, 14):
        put(g, 11, y, 'c'); put(g, 12, y, 'c')
    for i in range(6):
        put(g, 11 - i, 9 - i, 'c'); put(g, 10 - i, 9 - i, 'c')
        put(g, 12 + i, 9 - i, 'a'); put(g, 13 + i, 9 - i, 'a')
    # tip on the chosen (left) branch
    for d in range(3):
        put(g, 4 - d + 1, 3 + d, 'c'); put(g, 5 + d, 3, 'c')
    for y in range(16, h):
        put(g, 11, y, 'a'); put(g, 12, y, 'a')
    return done(g)

def check_flag(w=14, h=24):
    """checkpoint post with a chequered flag (left one; mirrored for right)"""
    g = blank(w, h)
    for y in range(0, 7):
        for x in range(1, w):
            put(g, x, y, 'c' if ((x - 1) // 2 + y // 2) % 2 else 'a')
    for y in range(0, h):
        put(g, 0, y, 'b')
    put(g, 0, 0, 'c')
    return done(g)


