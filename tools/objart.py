"""Roadside objects, drawn procedurally as character grids (see art.py).

SUNSET RUN, second art pass.  The shapes take their cue from the classic
1980s arcade road movies (lush leaning palms, white Mediterranean windmills,
round-crowned trees, ruined columns, red-on-white curve warnings, green
junction boards), but every pixel here is generated by the code below.

Each object uses one sprite palette: a = dark, b = main, c = light.
"""
import math

def blank(w, h):
    return [['.'] * w for _ in range(h)]

def put(g, x, y, ch):
    if 0 <= y < len(g) and 0 <= x < len(g[0]):
        g[y][x] = ch

def done(g):
    return [''.join(r) for r in g]

